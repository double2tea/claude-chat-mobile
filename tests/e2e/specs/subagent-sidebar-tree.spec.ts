import { expect, test } from '@playwright/test';
import { captureUserMessages, expectNoBrowserErrors, gotoMock } from '../../helpers/playwright';
import { expandWorkspace, MAIN_WORKSPACE, openSessionsSidebar, workspaceSubtree } from '../../helpers/sidebar-ui';

test.use({ viewport: { width: 393, height: 852 } });

test('手机抽屉按主会话、子代理和续聊分层，搜索保留归属', async ({ page }, testInfo) => {
  await gotoMock(page);
  expect((await page.request.post('/__arm-subagent-family')).ok()).toBe(true);
  await openSessionsSidebar(page);
  await expandWorkspace(page, MAIN_WORKSPACE);
  const workspace = workspaceSubtree(page, MAIN_WORKSPACE);
  const family = workspace.getByTestId('session-family');
  const disclosure = family.getByTestId('session-subagent-forks');
  const agent = disclosure.getByTestId('session-agent-branch');
  const continuations = agent.getByTestId('session-row');
  await expect(family.locator(':scope > [data-session-id="mock-session-archived"]')).toContainText('子任务启动');
  await expect(disclosure).toHaveJSProperty('open', true);
  await expect(agent.getByTestId('session-subagent-link')).toContainText('Explore');
  await expect(continuations).toHaveCount(2);
  await expect(continuations.first()).toContainText('确认原始任务');
  await expect(continuations.last()).toContainText('核对工作进度');
  await expect(workspace.locator('[data-subagent-fork]')).toHaveCount(2);
  await testInfo.attach('会话树', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' });

  await disclosure.locator('summary').click();
  await expect(continuations.first()).toBeHidden();
  await disclosure.locator('summary').click();
  await expect(continuations.first()).toBeVisible();
  await workspace.getByTestId('session-search').fill('核对');
  await expect(continuations).toHaveCount(1);
  await expect(continuations.first()).toContainText('核对工作进度');
  await expect(family.locator(':scope > [data-session-id="mock-session-archived"]')).toBeVisible();

  await agent.getByTestId('session-subagent-link').click();
  const card = page.locator('.sa-view');
  await expect(card).toBeVisible();
  await expect(card.locator('.sa-flow')).toContainText('Scanning auth handlers');
  const bounds = await card.boundingBox();
  expect(bounds!.y).toBeGreaterThan(100);
  expect(bounds!.width).toBeLessThanOrEqual(393);
  await testInfo.attach('子代理卡片', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' });
  await card.locator('[data-sa="close"]').click();
  await expect(card).toBeHidden();
  await expectNoBrowserErrors(page);
});

test('原子代理与新分支各自收到同一张卡片指定的消息', async ({ page }, testInfo) => {
  const sent = captureUserMessages(page);
  await gotoMock(page);
  expect((await page.request.post('/__arm-subagent-family')).ok()).toBe(true);
  await openSessionsSidebar(page);
  await expandWorkspace(page, MAIN_WORKSPACE);
  const workspace = workspaceSubtree(page, MAIN_WORKSPACE);
  const agent = workspace.getByTestId('session-agent-branch');
  const branchRows = agent.getByTestId('session-row');
  await expect(branchRows).toHaveCount(2);
  await agent.getByTestId('session-subagent-link').click();
  const card = page.locator('.sa-view');
  const input = card.getByRole('textbox');
  const send = card.getByRole('button', { name: '继续原子代理' });
  await input.fill('模拟驾驶冲突');
  await send.click();
  await expect(card.getByRole('status')).toContainText('驾驶权');
  await expect(input).toHaveValue('模拟驾驶冲突');
  await card.locator('[data-sa="close"]').click();
  await expect(card).toBeHidden();
  await openSessionsSidebar(page);
  await expect(branchRows).toHaveCount(2);
  await agent.getByTestId('session-subagent-link').click();
  await expect(input).toHaveValue('模拟驾驶冲突');
  await input.fill('请复核这个镜头');
  await send.click();
  await expect(card.locator('.sa-flow')).toContainText('原子代理回复：请复核这个镜头');
  await expect(input).toHaveValue('');
  await expect(branchRows).toHaveCount(2);
  expect(sent).toHaveLength(0);

  await input.fill('在分支继续这个镜头');
  await card.locator('.sa-send-options summary').click();
  const fork = card.getByRole('button', { name: /新开分支/ });
  await expect(fork).toBeVisible();
  const bounds = await fork.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(393);
  await testInfo.attach('子代理发送菜单', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' });
  await fork.click();
  await expect(card).toBeHidden();
  expect(sent).toHaveLength(1);
  expect(sent[0]).toMatchObject({ text: '在分支继续这个镜头', sessionId: 'session_branch_1', instanceId: 'inst_branch_1' });
  await openSessionsSidebar(page);
  await expect(branchRows).toHaveCount(3);
  await expect(agent.locator('[data-session-id="session_branch_1"]')).toContainText('子代理独立分支');
  await agent.getByTestId('session-subagent-link').click();
  await expect(card.locator('.sa-flow')).toContainText('原子代理回复：请复核这个镜头');
  await expect(card.locator('.sa-flow')).not.toContainText('在分支继续这个镜头');
  await expectNoBrowserErrors(page);
});

test('原位续聊断线后取回原回执，相同内容可主动再发', async ({ page }, testInfo) => {
  await gotoMock(page);
  expect((await page.request.post('/__arm-subagent-family?dropRelayAck=1')).ok()).toBe(true);
  await openSessionsSidebar(page);
  await expandWorkspace(page, MAIN_WORKSPACE);
  const agent = workspaceSubtree(page, MAIN_WORKSPACE).getByTestId('session-agent-branch');
  await agent.getByTestId('session-subagent-link').click();
  const card = page.locator('.sa-view');
  const input = card.getByRole('textbox');
  const send = card.getByRole('button', { name: '继续原子代理' });
  const reply = card.getByText('原子代理回复：断线后续聊', { exact: true });
  const reconnected = page.waitForEvent('websocket');
  await input.fill('断线后续聊');
  await send.click();
  await expect(card.locator('.sa-send-status')).toHaveClass(/is-error/);
  await reconnected;
  await expect(input).toHaveValue('断线后续聊');
  await send.click();
  await expect(reply).toHaveCount(1);
  await expect(input).toHaveValue('');
  await testInfo.attach('断线后找回同一条回复', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' });
  await input.fill('断线后续聊');
  await send.click();
  await expect(reply).toHaveCount(2);
  await expect(input).toHaveValue('');
  await expect(agent.getByTestId('session-row')).toHaveCount(2);
  await expectNoBrowserErrors(page);
});

test('分支实例被回收后续接同一会话并重试原消息', async ({ page }, testInfo) => {
  const sent = captureUserMessages(page);
  await gotoMock(page);
  expect((await page.request.post('/__arm-subagent-family?reclaimBranch=1')).ok()).toBe(true);
  await openSessionsSidebar(page);
  await expandWorkspace(page, MAIN_WORKSPACE);
  const agent = workspaceSubtree(page, MAIN_WORKSPACE).getByTestId('session-agent-branch');
  await agent.getByTestId('session-subagent-link').click();
  const card = page.locator('.sa-view');
  const input = card.getByRole('textbox');
  const fork = card.getByRole('button', { name: /新开分支/ });
  await input.fill('向同一个分支重试');
  await card.locator('.sa-send-options summary').click();
  await fork.click();
  await expect(card.locator('.sa-send-status')).toHaveClass(/is-error/);
  await expect(input).toHaveValue('向同一个分支重试');
  await testInfo.attach('实例回收后保留分支草稿', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' });
  await card.locator('.sa-send-options summary').click();
  await fork.click();
  await expect(card).toBeHidden();
  expect(sent).toHaveLength(2);
  expect(sent[0]).toMatchObject({ instanceId: 'inst_branch_1', sessionId: 'session_branch_1', text: '向同一个分支重试' });
  expect(sent[0].clientMessageId).toBeTruthy();
  expect(sent[1]).toMatchObject({ ...sent[0], instanceId: 'inst_branch_restored' });
  await openSessionsSidebar(page);
  await expect(agent.locator('[data-session-id="session_branch_1"]')).toHaveCount(1);
  await expect(agent.getByTestId('session-row')).toHaveCount(3);
  await expectNoBrowserErrors(page);
});
